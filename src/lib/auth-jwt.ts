import crypto from 'crypto';
import { cookies } from 'next/headers';
import { NextRequest } from 'next/server';

export interface TenantSession {
  db_name: string;
  app_base_url: string;
  user_id: number | string;
  user_level?: number | string;
  iat?: number;
  exp: number;
}

export const ZENRO_TENANT_COOKIE = 'zenro_tenant_session';

// Safe base64url decode helper
function base64UrlDecode(str: string): string {
  let base64 = str.replace(/-/g, '+').replace(/_/g, '/');
  while (base64.length % 4) {
    base64 += '=';
  }
  return Buffer.from(base64, 'base64').toString('utf-8');
}

// Safe base64url encode helper
function base64UrlEncode(buffer: Buffer | string): string {
  const b = Buffer.isBuffer(buffer) ? buffer : Buffer.from(buffer, 'utf-8');
  return b
    .toString('base64')
    .replace(/=/g, '')
    .replace(/\+/g, '-')
    .replace(/\//g, '_');
}

export function getJwtSecret(): string {
  const secret = process.env.ZENRO_JWT_SECRET;
  if (!secret) {
    throw new Error('ZENRO_JWT_SECRET is not configured in .env.local');
  }
  return secret;
}

/**
 * Verify a JWT token generated by a Zenro Payroll PHP application
 */
export function verifyTenantToken(token: string): {
  valid: boolean;
  session?: TenantSession;
  error?: string;
} {
  try {
    if (!token || typeof token !== 'string') {
      return { valid: false, error: 'No token provided' };
    }

    const parts = token.trim().split('.');
    if (parts.length !== 3) {
      return { valid: false, error: 'Malformed token structure' };
    }

    const [headerB64, payloadB64, signatureB64] = parts;
    const secret = getJwtSecret();

    // Verify signature
    const expectedSig = crypto
      .createHmac('sha256', secret)
      .update(`${headerB64}.${payloadB64}`)
      .digest();

    const expectedSigB64 = base64UrlEncode(expectedSig);

    // Timing-safe comparison to prevent timing attacks
    const sigA = Buffer.from(signatureB64);
    const sigB = Buffer.from(expectedSigB64);
    if (sigA.length !== sigB.length || !crypto.timingSafeEqual(sigA, sigB)) {
      return { valid: false, error: 'Invalid cryptographic signature' };
    }

    // Parse header and payload
    const payloadStr = base64UrlDecode(payloadB64);
    const payload = JSON.parse(payloadStr) as TenantSession;

    // Check expiration
    const now = Math.floor(Date.now() / 1000);
    if (!payload.exp || payload.exp < now) {
      return { valid: false, error: 'Token has expired' };
    }

    // Validate db_name: must be alphanumeric and underscores only
    if (!payload.db_name || !/^[a-zA-Z0-9_]+$/.test(payload.db_name)) {
      return { valid: false, error: 'Invalid or missing db_name in token' };
    }

    // Validate app_base_url
    if (!payload.app_base_url || (!payload.app_base_url.startsWith('http://') && !payload.app_base_url.startsWith('https://'))) {
      return { valid: false, error: 'Invalid app_base_url in token' };
    }

    return { valid: true, session: payload };
  } catch (err: any) {
    return { valid: false, error: err.message || 'Token verification failed' };
  }
}

/**
 * Sign a tenant session token (useful for local testing or session re-minting)
 */
export function signTenantToken(
  sessionData: Omit<TenantSession, 'exp' | 'iat'>,
  ttlSeconds = 8 * 3600
): string {
  const secret = getJwtSecret();
  const now = Math.floor(Date.now() / 1000);

  const header = base64UrlEncode(JSON.stringify({ typ: 'JWT', alg: 'HS256' }));
  const payload = base64UrlEncode(
    JSON.stringify({
      ...sessionData,
      iat: now,
      exp: now + ttlSeconds,
    })
  );

  const signature = base64UrlEncode(
    crypto.createHmac('sha256', secret).update(`${header}.${payload}`).digest()
  );

  return `${header}.${payload}.${signature}`;
}

/**
 * Extract verified tenant session from Next.js server Request (cookie or header or query)
 */
export function getTenantSessionFromRequest(req: NextRequest): TenantSession | null {
  // 1. Check authorization header
  const authHeader = req.headers.get('authorization');
  if (authHeader && authHeader.startsWith('Bearer ')) {
    const token = authHeader.substring(7);
    const result = verifyTenantToken(token);
    if (result.valid && result.session) return result.session;
  }

  // 2. Check query param ?token=
  const urlToken = req.nextUrl.searchParams.get('token');
  if (urlToken) {
    const result = verifyTenantToken(urlToken);
    if (result.valid && result.session) return result.session;
  }

  // 3. Check session cookie
  const cookieToken = req.cookies.get(ZENRO_TENANT_COOKIE)?.value;
  if (cookieToken) {
    const result = verifyTenantToken(cookieToken);
    if (result.valid && result.session) return result.session;
  }

  return null;
}
